/**
 * Calculates financial feasibility and speedup from video analysis
 */
export function calculateVideoRobotization(
  preset: VideoDatasetPreset,
  shiftsPerDay: number = 2,
  laborHourlyRate: number = 36,
): VideoAnalysisResult {
  const annualHours = shiftsPerDay * 7.5 * 250; // 250 work days
  const manualHourlyThroughput = Math.round(3600 / preset.manualTaktTimeSec);
  const roboticHourlyThroughput = Math.round(3600 / preset.projectedRobotCycleTimeSec);

  const speedupMultiplier = Number(
    (preset.manualTaktTimeSec / preset.projectedRobotCycleTimeSec).toFixed(2),
  );
  const throughputGainPercent = Math.round(
    ((roboticHourlyThroughput - manualHourlyThroughput) / manualHourlyThroughput) * 100,
  );

  // Labor cost
  const annualManualLaborCost = preset.operatorCount * annualHours * laborHourlyRate;
  const annualMaintenance = 7500;
  const annualLaborSavings = annualManualLaborCost - annualMaintenance;

  // Turnkey investment estimate based on robot type
  let capitalCost = 88000;
  if (preset.recommendedRobot.includes("ARM-25")) capitalCost = 125000;
  else if (preset.recommendedRobot.includes("ARM-12")) capitalCost = 98000;
  else if (preset.recommendedRobot.includes("DELTA")) capitalCost = 82000;
  else if (preset.recommendedRobot.includes("SCARA")) capitalCost = 74000;

  const paybackMonths = Number(((capitalCost / annualLaborSavings) * 12).toFixed(1));

  return {
    presetId: preset.id,
    manualCycleTimeSec: preset.manualTaktTimeSec,
    projectedRobotCycleTimeSec: preset.projectedRobotCycleTimeSec,
    cycleTimeReductionSec: Number((preset.manualTaktTimeSec - preset.projectedRobotCycleTimeSec).toFixed(2)),
    speedupMultiplier,
    throughputHourlyManual: manualHourlyThroughput,
    throughputHourlyRobotic: roboticHourlyThroughput,
    throughputGainPercent,
    ergoRiskReductionPercent: 100,
    recommendedRobotModel: preset.recommendedRobot,
    recommendedEndEffector: preset.recommendedEndEffector,
    estimatedCapitalCostUsd: capitalCost,
    annualLaborSavingsUsd: Math.round(annualLaborSavings),
    paybackMonths: Math.max(2.8, paybackMonths),
  };
}
